-- Sammy knowledge improvements (run in Supabase SQL Editor)
-- Safe to re-run. Service-role credentials must remain server-side only.

create table if not exists public.sammy_knowledge (
  question_key text primary key,
  answer text not null,
  verified boolean not null default false,
  updated_at timestamptz not null default now()
);

alter table public.sammy_knowledge
  add column if not exists source_label text,
  add column if not exists source_url text,
  add column if not exists verified_at timestamptz,
  add column if not exists expires_at timestamptz;

alter table public.sammy_knowledge enable row level security;
revoke all on table public.sammy_knowledge from anon, authenticated;
grant all on table public.sammy_knowledge to service_role;

-- Corrections are suggestions only. They are NOT automatically trusted answers.
create table if not exists public.sammy_knowledge_suggestions (
  id bigint generated by default as identity primary key,
  question text not null,
  suggested_answer text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);
alter table public.sammy_knowledge_suggestions enable row level security;
revoke all on table public.sammy_knowledge_suggestions from anon, authenticated;
grant all on table public.sammy_knowledge_suggestions to service_role;


-- Migrate the sample aliases from the earlier v7 format without losing answers.
update public.sammy_knowledge as old_row
set question_key = regexp_replace(old_row.question_key, '^v7:', 'v8:')
where old_row.question_key like 'v7:%'
  and not exists (
    select 1 from public.sammy_knowledge as current_row
    where current_row.question_key = regexp_replace(old_row.question_key, '^v7:', 'v8:')
  );

-- Example facts. Add aliases as separate question_key rows.
insert into public.sammy_knowledge
  (question_key, answer, verified, source_label, verified_at)
values
  ('v8:what is my name', 'Your name is Sammy.', true, 'Sammy configured facts', now()),
  ('v8:what is my favorite brainrot', 'Your favorite Brainrot is Meowl.', true, 'Sammy configured facts', now()),
  ('v8:what is my favorite mutation', 'Your favorite mutation is Ying Yang.', true, 'Sammy configured facts', now()),
  ('v8:what is my favorite kind of tacos', 'Your favorite taco is Carne Asada.', true, 'Sammy configured facts', now())
on conflict (question_key) do update
set answer = excluded.answer,
    verified = excluded.verified,
    source_label = excluded.source_label,
    verified_at = now(),
    updated_at = now();

